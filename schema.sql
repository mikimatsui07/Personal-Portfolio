CREATE TABLE IF NOT EXISTS certificates (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(160) NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    photo VARCHAR(255),
    obtained_at DATE NOT NULL,
    created_at TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Manila')
);

-- Added later: issuer, credential details, skills and expiry.
ALTER TABLE certificates ADD COLUMN IF NOT EXISTS issuer VARCHAR(160) NOT NULL DEFAULT '';
ALTER TABLE certificates ADD COLUMN IF NOT EXISTS credential_id VARCHAR(120) NOT NULL DEFAULT '';
ALTER TABLE certificates ADD COLUMN IF NOT EXISTS credential_url VARCHAR(2048) NOT NULL DEFAULT '';
ALTER TABLE certificates ADD COLUMN IF NOT EXISTS skills TEXT NOT NULL DEFAULT '';
ALTER TABLE certificates ADD COLUMN IF NOT EXISTS expires_at DATE;

-- Contact form messages. Times are stored in Philippine time, like XAMPP did.
CREATE TABLE IF NOT EXISTS messages (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL,
    message TEXT NOT NULL,
    created_at TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Manila')
);

-- Supabase also exposes tables through its public REST API. Row Level
-- Security with no policies blocks that API completely; the Flask app
-- connects directly as the database owner, which is not affected.
ALTER TABLE admins ENABLE ROW LEVEL SECURITY;
ALTER TABLE projects ENABLE ROW LEVEL SECURITY;
ALTER TABLE project_media ENABLE ROW LEVEL SECURITY;
ALTER TABLE profile ENABLE ROW LEVEL SECURITY;
ALTER TABLE certificates ENABLE ROW LEVEL SECURITY;
ALTER TABLE messages ENABLE ROW LEVEL SECURITY;
