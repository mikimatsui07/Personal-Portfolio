-- Mik Portfolio — PostgreSQL schema for Supabase.
-- Run once (setup_supabase.py does it for you, or paste into the
-- Supabase SQL Editor). Safe to run again: it only creates what is missing.

-- Admin accounts. Passwords are Werkzeug hashes.
CREATE TABLE IF NOT EXISTS admins (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(100) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS projects (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(160) NOT NULL,
    description TEXT NOT NULL,
    technologies TEXT NOT NULL DEFAULT '',
    project_link VARCHAR(2048) NOT NULL DEFAULT '',
    created_at DATE NOT NULL
);

-- Added later: one category per project (the list lives in app.py,
-- ProjectCategories). Projects that existed before start as websites.
ALTER TABLE projects ADD COLUMN IF NOT EXISTS category VARCHAR(40) NOT NULL DEFAULT 'websites';

-- Gallery files of each project, in display order.
CREATE TABLE IF NOT EXISTS project_media (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id INTEGER NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
    filename VARCHAR(255) NOT NULL,
    position INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Manila')
);

CREATE INDEX IF NOT EXISTS project_media_project ON project_media (project_id);

-- The single row (id = 1) with the hero and About content.
CREATE TABLE IF NOT EXISTS profile (
    id INTEGER PRIMARY KEY CHECK (id = 1),
    hero_name VARCHAR(60),
    hero_intro TEXT,
    hero_picture VARCHAR(255),
    description TEXT NOT NULL,
    picture VARCHAR(255),
    skills TEXT NOT NULL,
    updated_at TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Manila')
);

